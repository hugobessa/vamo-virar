export type Lang = "pt" | "en";
const tables: Record<Lang, Record<StringKey, string>> = { pt, en };

export function translator(lang: Lang) {
  const table = tables[lang];
  return (k: StringKey) => table[k];
}

/** Every string in a language, for checks over the whole table. */
export function allStrings(lang: Lang): string[] {
  return Object.values(tables[lang]);
}

export function pickLang(languageCode: string | null | undefined): Lang {
  return languageCode === "pt" ? "pt" : "en";
}

/** Maps a reducer rejection reason to a sentence for people. */
export function reasonKey(reason: string): StringKey {
  const k = `why_${reason}` as StringKey;
  return k in pt ? k : "why_other";
}
