export type StringKey = keyof typeof pt;

export function translator() {
  return (k: StringKey) => pt[k];
}

/** Every string, for checks over the whole table. */
export function allStrings(): string[] {
  return Object.values(pt);
}

/** Maps a reducer rejection reason to a sentence for people. */
export function reasonKey(reason: string): StringKey {
  const k = `why_${reason}` as StringKey;
  return k in pt ? k : "why_other";
}
